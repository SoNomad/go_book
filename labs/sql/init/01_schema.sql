-- Схема учебного интернет-магазина.
-- Все суммы — в numeric (никогда не float!), время — timestamptz (с часовым поясом).

CREATE TABLE categories (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text    NOT NULL UNIQUE
);

CREATE TABLE users (
    id         integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      text        NOT NULL UNIQUE,
    name       text        NOT NULL,
    country    text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE products (
    id          integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id integer       NOT NULL REFERENCES categories (id),
    name        text          NOT NULL,
    price       numeric(10,2) NOT NULL CHECK (price >= 0),
    stock       integer       NOT NULL DEFAULT 0 CHECK (stock >= 0)
);

CREATE TABLE orders (
    id         integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer     NOT NULL REFERENCES users (id),
    status     text        NOT NULL CHECK (status IN ('new', 'paid', 'shipped', 'cancelled')),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE order_items (
    order_id   integer       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id integer       NOT NULL REFERENCES products (id),
    quantity   integer       NOT NULL CHECK (quantity > 0),
    unit_price numeric(10,2) NOT NULL,           -- цена НА МОМЕНТ покупки (товар может подорожать)
    PRIMARY KEY (order_id, product_id)
);

-- Индекс по внешнему ключу: PostgreSQL НЕ создаёт его автоматически.
CREATE INDEX idx_orders_user_id ON orders (user_id);
CREATE INDEX idx_products_category_id ON products (category_id);
